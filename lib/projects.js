// Helper lookup functions
export function getAllProjects() {
  return PROJECTS
}

export function getAllProjectSlugs() {
  return PROJECTS.map(p => ({ slug: p.slug || p.id }))
}

export function getProjectBySlug(slug) {
  if (!slug) return null
  const clean = slug.toLowerCase().trim()
  return PROJECTS.find(p => (p.slug && p.slug.toLowerCase() === clean) || p.id.toLowerCase() === clean) || null
}

export function getRelatedProjects(currentSlug, limit = 3) {
  const all = getAllProjects()
  return all.filter(p => (p.slug || p.id) !== currentSlug).slice(0, limit)
}
